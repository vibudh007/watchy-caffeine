"""Pack the approved maximalist artwork and clock numerals for the renderer."""

import importlib.util
from pathlib import Path

from PIL import Image

root = Path(__file__).resolve().parents[1]
reference = Path(__file__).with_name("render-maximalist.py")
spec = importlib.util.spec_from_file_location("render_maximalist", reference)
study = importlib.util.module_from_spec(spec)
spec.loader.exec_module(study)

static_labels = {"MENU", "LOCAL TIME", "BATTERY", "CHARGE", "STEPS", "STEPS TODAY"}


class StaticFace(study.Face):
    """Keep the fixed panels, reference rules and left-side Menu hint."""

    def text(self, x, y, value, *args, **kwargs):
        if value in static_labels and not (value == "LOCAL TIME" and (x, y) == (32, 36)):
            super().text(x, y, value, *args, **kwargs)

    def digits(self, *args, **kwargs):
        return None

    def battery(self, *args, **kwargs):
        return None


def hex_rows(data):
    for start in range(0, len(data), 16):
        yield "    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 16]) + ","


def templates():
    study.Face = StaticFace
    study.pixel_digits = lambda *_: None
    for slug, render in study.FACES.items():
        settings = {"divider": "c"} if slug == "patchbay" else {}
        image = render(study.DATES["main"], False, **settings)
        assert image.size == (200, 200) and len(image.tobytes()) == 5000
        yield slug.replace("-", "_"), image.tobytes()


def glyphs(size):
    font = study.font("clock", size, 700)
    blob, records = bytearray(), []
    for digit in "0123456789":
        glyph = font.getmask(digit, mode="1")
        image = Image.new("1", glyph.size, 0)
        image.putdata(list(glyph))
        crop = image.crop(image.getbbox())
        records.append((len(blob), crop.width, crop.height))
        blob += crop.tobytes()
    return records, blob


def main():
    target = root / "source/watch/face_max_data.inc"
    with target.open("w") as output:
        output.write("/* Generated by .work/ux-round-two/pack-maximalist.py. */\n")
        for name, image in templates():
            output.write(f"\nstatic const uint8_t {name}_art[WATCH_FRAME_SIZE] = {{\n")
            output.write("\n".join(hex_rows(image)) + "\n};\n")
        for size in (52, 55, 59, 64):
            records, blob = glyphs(size)
            output.write(f"\nstatic const digit_glyph_t digits{size}[] = {{\n")
            for offset, width, height in records:
                output.write(f"    {{{offset}, {width}, {height}}},\n")
            output.write(f"}};\n\nstatic const uint8_t pixels{size}[] = {{\n")
            output.write("\n".join(hex_rows(blob)) + "\n};\n")


if __name__ == "__main__":
    main()
