"""Generate the fixed 1-bit Watchy glyph tables from local font files."""

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


PROJECT = Path(__file__).resolve().parents[1]
ASCII = "".join(map(chr, range(32, 127))) + "·–’↑↓"
DIGITS = "0123456789"
PROFILES = (
    ("UI_TINY", "tiny", "Geist", 11, 720, None),
    ("UI_SMALL", "small", "Geist", 13, 660, None),
    ("UI_BODY", "body", "Geist", 14, 680, None),
    ("UI_MENU", "menu", "Geist", 17, 680, None),
    ("UI_TITLE", "title", "Geist", 21, 720, None),
    ("UI_LARGE", "large", "Geist", 38, 730, " " + DIGITS + ",%.?'!CSTaceghimprstuw"),
    ("UI_DATE", "date", "Geist", 32, 710, " " + DIGITS + "-?"),
    ("UI_NUMBER", "number", "Geist", 55, 720, " " + DIGITS + "%?"),
    ("UI_MONO_TINY", "mono_tiny", "GeistMono", 11, 680, None),
    ("UI_MONO_SMALL", "mono_small", "GeistMono", 15, 690, None),
    ("UI_MONO_MEDIUM", "mono_medium", "GeistMono", 22, 680, " " + DIGITS + "?:+/-"),
    ("UI_MONO_LARGE", "mono_large", "GeistMono", 36, 715, " " + DIGITS + "?:"),
    ("UI_MONO_HERO", "mono_hero", "GeistMono", 48, 720, " " + DIGITS + "?:"),
    (None, "clock_ledger", "BarlowSemiCondensed-Bold", 73, None, DIGITS),
    (None, "clock_split", "BarlowSemiCondensed-Bold", 100, None, DIGITS),
)


def rasterize(font, character, offset):
    """Return integer placement, 1/64-pixel advance and MSB-first row bytes."""
    advance = round(font.getlength(character) * 64)
    left, top, right, bottom = font.getbbox(character)
    if right <= left or bottom <= top:
        return (offset, advance, 0, 0, 0, 0), b""
    image = Image.new("1", (right - left, bottom - top))
    ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=255)
    ink = image.getbbox()
    if ink is None:
        return (offset, advance, 0, 0, 0, 0), b""
    left += ink[0]
    top += ink[1]
    image = image.crop(ink)
    assert 0 <= offset <= 65535 and 0 < advance <= 65535
    assert -128 <= left < 128 and 0 <= top <= 255
    assert image.width <= 255 and image.height <= 255
    return (offset, advance, image.width, image.height, top, left), image.tobytes()


def tables(font_dir, name, family, size, weight, characters):
    """Write declarations for one compact bitmap and its glyph index."""
    font = ImageFont.truetype(str(font_dir / f"{family}.ttf"), size)
    if weight is not None:
        font.set_variation_by_axes([weight])
    pixels = bytearray()
    glyphs = []
    for character in characters:
        metadata, bitmap = rasterize(font, character, len(pixels))
        pixels.extend(bitmap)
        glyphs.append(f"    {{{', '.join(map(str, metadata))}}}, // {character!r}")
    raster = []
    for i in range(0, len(pixels), 16):
        raster.append("    " + ", ".join(f"0x{x:02x}" for x in pixels[i:i + 16]) + ",")
    return "\n".join([
        f"static const ui_glyph_t {name}_glyphs[] = {{", *glyphs, "};",
        f"static const uint8_t {name}_pixels[] = {{", *raster, "};", "",
    ])


def main():
    """Keep generation project-local and emit the index in enum order."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_dir", type=Path, help="Project directory with the three TTF input files")
    args = parser.parse_args()
    font_dir = args.font_dir.resolve()
    if not font_dir.is_relative_to(PROJECT):
        parser.error("font directory must be inside the project")
    parts = ["// Generated by tools/make_watchy_ui_font.py. See ui_font-license.txt.\n"]
    index = []
    for key, name, family, size, weight, alphabet in PROFILES:
        parts.append(tables(font_dir, name, family, size, weight, alphabet or ASCII))
        if key:
            codes = f'"{alphabet}"' if alphabet else "NULL"
            index.append(f"    [{key}] = {{{name}_glyphs, {name}_pixels, {codes}}},")
    parts.extend(["static const ui_bitmap_font_t fonts[UI_FONT_COUNT] = {", *index, "};", ""])
    (PROJECT / "source/watch/ui_font_data.inc").write_text("\n".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
